-- IBM Db2 Schema for FixRank
-- Compatible with Db2 LUW 12.1+ and Community Edition

CREATE TABLE SOLUTIONS (
  ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  PROBLEM_ID VARCHAR(64) NOT NULL,
  TITLE VARCHAR(255) NOT NULL,
  STEPS CLOB NOT NULL,
  WORKED INTEGER NOT NULL DEFAULT 0,
  FAILED INTEGER NOT NULL DEFAULT 0,
  SOURCE VARCHAR(32) NOT NULL DEFAULT 'AI_ESTIMATE',
  CATEGORY VARCHAR(64) DEFAULT 'GENERAL',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE FEEDBACK (
  ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  SOLUTION_ID INTEGER NOT NULL,
  SESSION_ID VARCHAR(64) NOT NULL,
  OUTCOME VARCHAR(8) NOT NULL,
  USER_OS VARCHAR(32) DEFAULT 'UNKNOWN',
  CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT UQ_VOTE UNIQUE (SOLUTION_ID, SESSION_ID),
  CONSTRAINT FK_SOLUTION FOREIGN KEY (SOLUTION_ID) REFERENCES SOLUTIONS(ID) ON DELETE CASCADE
);

CREATE INDEX IDX_SOL_PROB ON SOLUTIONS(PROBLEM_ID);
CREATE INDEX IDX_FDB_SOL ON FEEDBACK(SOLUTION_ID);
CREATE INDEX IDX_FDB_SESS ON FEEDBACK(SESSION_ID);
