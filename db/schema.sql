-- ============================================================================
-- IBM Db2 Schema for Resolve AI
-- Compatible with Db2 LUW 12.1+ and IBM Db2 on Cloud
-- Idempotent and safe to run repeatedly.
-- ============================================================================

-- 1. Table: SOLUTIONS
-- Canonical and community fixes keyed by string identifier (e.g. "db2-30082").
-- Steps stored as a JSON array of strings.
BEGIN
  DECLARE CONTINUE HANDLER FOR SQLSTATE '42710' BEGIN END; -- Object already exists
  EXECUTE IMMEDIATE '
    CREATE TABLE SOLUTIONS (
      ID VARCHAR(64) NOT NULL PRIMARY KEY,
      TECH VARCHAR(32) NOT NULL,
      ERROR_CODE VARCHAR(64) DEFAULT '''',
      ERROR_TYPE VARCHAR(64) NOT NULL,
      TITLE VARCHAR(255) NOT NULL,
      SEARCH_TEXT CLOB NOT NULL,
      STEPS CLOB NOT NULL,
      SOURCE VARCHAR(32) NOT NULL DEFAULT ''AI_ESTIMATE'',
      CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  ';
END;
/

-- 2. Table: FEEDBACK
-- User votes (worked/failed) tied to solution slug.
-- Enforces uniqueness per (SOLUTION_ID, SESSION_ID) to prevent duplicate votes.
BEGIN
  DECLARE CONTINUE HANDLER FOR SQLSTATE '42710' BEGIN END;
  EXECUTE IMMEDIATE '
    CREATE TABLE FEEDBACK (
      ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      SOLUTION_ID VARCHAR(64) NOT NULL,
      SESSION_ID VARCHAR(64) NOT NULL,
      OUTCOME VARCHAR(8) NOT NULL,
      USER_OS VARCHAR(32) DEFAULT ''UNKNOWN'',
      CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      CONSTRAINT CHK_FEEDBACK_OUTCOME CHECK (OUTCOME IN (''worked'',''failed'')),
      CONSTRAINT UQ_VOTE UNIQUE (SOLUTION_ID, SESSION_ID),
      CONSTRAINT FK_SOLUTION_ID FOREIGN KEY (SOLUTION_ID) REFERENCES SOLUTIONS(ID) ON DELETE CASCADE
    )
  ';
END;
/

-- 3. Table: SEARCH_LOG
-- Persistent audit log of search queries, latency metrics, and top retrieved fix.
BEGIN
  DECLARE CONTINUE HANDLER FOR SQLSTATE '42710' BEGIN END;
  EXECUTE IMMEDIATE '
    CREATE TABLE SEARCH_LOG (
      ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      QUERY_TEXT VARCHAR(300),
      TECH VARCHAR(32),
      ERROR_CODE VARCHAR(64),
      CONFIDENCE INTEGER,
      LATENCY_MS DECIMAL(9,2),
      TOP_SOLUTION_ID VARCHAR(64),
      CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  ';
END;
/

