-- 5. View: SOLUTION_STATS
-- Computes real-time WORKED, FAILED, VOTES, and LAST_VERIFIED dynamically from FEEDBACK.
-- Left join guarantees zero-vote fixes still appear with WORKED=0 and FAILED=0.
CREATE OR REPLACE VIEW SOLUTION_STATS (SOLUTION_ID, WORKED, FAILED, VOTES, LAST_VERIFIED) AS
SELECT 
  s.ID AS SOLUTION_ID,
  COALESCE(SUM(CASE WHEN f.OUTCOME = 'worked' THEN 1 ELSE 0 END), 0) AS WORKED,
  COALESCE(SUM(CASE WHEN f.OUTCOME = 'failed' THEN 1 ELSE 0 END), 0) AS FAILED,
  COALESCE(COUNT(f.ID), 0) AS VOTES,
  MAX(f.CREATED_AT) AS LAST_VERIFIED
FROM SOLUTIONS s
LEFT JOIN FEEDBACK f ON s.ID = f.SOLUTION_ID
GROUP BY s.ID;
/
